/**
 * Generate a deploy-on-merge CI workflow.
 *
 * Produces a YAML string for a given provider+app combination.
 * Secrets are referenced by name only (e.g. ${{ secrets.MY_TOKEN }}) — never
 * inlined. The generated YAML is designed to pass actionlint.
 */

// ---------------------------------------------------------------------------
// Types
// ---------------------------------------------------------------------------

export type CiProvider = "github" | "vercel" | "cloudflare" | "fly" | "digitalocean" | "aws";

/** Known app kinds that affect the build/deploy steps. */
export type CiAppKind = "static" | "ssr" | "container";

export interface CiWorkflowOptions {
  /** CI host — currently only "github" (GitHub Actions) is implemented; others are reserved */
  ciHost?: "github";
  /** Deployment provider (where the app is deployed) */
  provider: CiProvider;
  /** Kind of app (affects build steps) */
  appKind?: CiAppKind;
  /** Node version for the workflow (default: "20") */
  nodeVersion?: string;
  /** Branch that triggers deploy (default: "main") */
  deployBranch?: string;
  /** Names of secrets the workflow needs — inserted as ${{ secrets.NAME }} only */
  secrets?: string[];
  /** Extra env vars that are safe to inline (non-secret values only) */
  env?: Record<string, string>;
  /** Workflow name override */
  workflowName?: string;
}

export interface CiWorkflowResult {
  /** File path where the workflow should be written */
  path: string;
  /** YAML content */
  yaml: string;
}

// ---------------------------------------------------------------------------
// Generator
// ---------------------------------------------------------------------------

/**
 * Generate a deploy-on-merge workflow.
 *
 * Returns the target file path and the YAML string. The caller is responsible
 * for writing the file to disk (after user approval).
 *
 * Secrets are referenced by name only — values never appear in the YAML.
 */
export function generateCiWorkflow(opts: CiWorkflowOptions): CiWorkflowResult {
  const ciHost = opts.ciHost ?? "github";
  if (ciHost !== "github") {
    throw new CiWorkflowError(`Unsupported CI host: ${ciHost}. Only "github" is implemented.`);
  }

  const branch = opts.deployBranch ?? "main";
  const nodeVersion = opts.nodeVersion ?? "20";
  const workflowName = opts.workflowName ?? `Deploy to ${opts.provider} on merge`;
  const appKind = opts.appKind ?? (opts.provider === "vercel" || opts.provider === "cloudflare" ? "static" : "container");

  const lines: string[] = [];

  // Header comment
  lines.push("# Generated by Kailashe — deploy-on-merge workflow");
  lines.push(`# Provider: ${opts.provider} | App kind: ${appKind}`);
  lines.push(`# Secrets are referenced by name only; set them in your repo settings.`);
  lines.push("");

  lines.push(`name: ${yamlString(workflowName)}`);
  lines.push("");

  // Trigger
  lines.push("on:");
  lines.push("  push:");
  lines.push("    branches:");
  lines.push(`      - ${branch}`);
  lines.push("");

  // Minimal permissions — least privilege
  lines.push("permissions:");
  lines.push("  contents: read");
  lines.push("");

  // Jobs
  lines.push("jobs:");
  lines.push("  deploy:");
  lines.push("    runs-on: ubuntu-latest");
  lines.push("    permissions:");
  lines.push("      contents: read");

  // Top-level env: only non-secret values
  if (opts.env && Object.keys(opts.env).length > 0) {
    lines.push("    env:");
    for (const [k, v] of Object.entries(opts.env)) {
      lines.push(`      ${k}: ${yamlString(v)}`);
    }
  }

  lines.push("    steps:");

  // Checkout
  lines.push("      - name: Checkout");
  lines.push("        uses: actions/checkout@v4");

  // Setup Node
  lines.push("      - name: Setup Node.js");
  lines.push("        uses: actions/setup-node@v4");
  lines.push("        with:");
  lines.push(`          node-version: ${yamlString(nodeVersion)}`);
  lines.push("          cache: pnpm");

  // Install
  lines.push("      - name: Install dependencies");
  lines.push("        run: pnpm install --frozen-lockfile");

  // Build
  lines.push("      - name: Build");
  lines.push("        run: pnpm build");

  // Provider-specific deploy step
  lines.push(...deployStepsForProvider(opts.provider, appKind, opts.secrets ?? []));

  const yaml = lines.join("\n") + "\n";

  // Validate that secrets appear only as ${{ secrets.NAME }} references
  validateSecretsByNameOnly(yaml, opts.secrets ?? []);

  return {
    path: ".github/workflows/deploy.yml",
    yaml,
  };
}

// ---------------------------------------------------------------------------
// Provider-specific deploy steps
// ---------------------------------------------------------------------------

function deployStepsForProvider(
  provider: CiProvider,
  _appKind: CiAppKind,
  secrets: string[],
): string[] {
  // Build the env block for secrets (by name only)
  const secretEnvLines: string[] = [];
  if (secrets.length > 0) {
    secretEnvLines.push("        env:");
    for (const s of secrets) {
      secretEnvLines.push(`          ${s}: ` + "${{ secrets." + s + " }}");
    }
  }

  switch (provider) {
    case "vercel":
      return [
        "      - name: Deploy to Vercel",
        "        run: npx vercel deploy --prod --yes",
        ...secretEnvLines,
      ];

    case "cloudflare":
      return [
        "      - name: Deploy to Cloudflare Pages",
        "        run: npx wrangler pages deploy ./dist --project-name ${{ env.CLOUDFLARE_PROJECT_NAME }}",
        ...secretEnvLines,
      ];

    case "fly":
      return [
        "      - name: Deploy to Fly.io",
        "        uses: superfly/flyctl-actions/setup-flyctl@master",
        "      - name: Deploy",
        "        run: flyctl deploy --remote-only",
        ...secretEnvLines,
      ];

    case "digitalocean":
      return [
        "      - name: Install doctl",
        "        uses: digitalocean/action-doctl@v2",
        "        with:",
        `          token: \${{ secrets.DIGITALOCEAN_ACCESS_TOKEN }}`,
        "      - name: Deploy to DigitalOcean App Platform",
        "        run: doctl apps create --spec .do/app.yaml || doctl apps update --spec .do/app.yaml $(doctl apps list --format ID --no-header | head -1)",
        ...secretEnvLines,
      ];

    case "aws":
      return [
        "      - name: Configure AWS credentials",
        "        uses: aws-actions/configure-aws-credentials@v4",
        "        with:",
        "          aws-region: ${{ env.AWS_REGION }}",
        "          role-to-assume: ${{ secrets.AWS_ROLE_TO_ASSUME }}",
        "      - name: Build and push image",
        "        run: |",
        "          aws ecr get-login-password --region ${{ env.AWS_REGION }} | docker login --username AWS --password-stdin ${{ env.ECR_REGISTRY }}",
        "          docker build -t ${{ env.ECR_REGISTRY }}/${{ env.ECR_REPOSITORY }}:${{ github.sha }} .",
        "          docker push ${{ env.ECR_REGISTRY }}/${{ env.ECR_REPOSITORY }}:${{ github.sha }}",
        ...secretEnvLines,
      ];

    default:
      return [
        "      - name: Deploy",
        `        run: echo "Deploy to ${provider} — configure this step for your provider"`,
        ...secretEnvLines,
      ];
  }
}

// ---------------------------------------------------------------------------
// Validation — secrets by name only
// ---------------------------------------------------------------------------

/**
 * Assert that no secret value is inlined in the YAML.
 * Secrets must only appear as ${{ secrets.NAME }}.
 *
 * This is a best-effort structural check: it verifies that every secret name
 * appears only inside the ${{ secrets.NAME }} pattern and that no line
 * contains a bare assignment of a known secret value.
 */
export function validateSecretsByNameOnly(yaml: string, secretNames: string[]): void {
  if (secretNames.length === 0) return;

  for (const name of secretNames) {
    // Every occurrence of the secret name must be inside ${{ secrets.NAME }}
    // We check that there is no line like `NAME: some-value` that inlines it.
    const lines = yaml.split("\n");
    for (const line of lines) {
      const trimmed = line.trim();
      // If a line assigns the secret name directly to a non-secrets value, flag it.
      // Valid pattern: `NAME: ${{ secrets.NAME }}`
      // Invalid pattern: `NAME: actual-secret-value` or `NAME: "value"`
      if (trimmed.startsWith(`${name}:`)) {
        const value = trimmed.slice(name.length + 1).trim();
        if (value && !value.includes("secrets.")) {
          throw new CiWorkflowError(
            `Secret "${name}" appears to be inlined on line: ${line.trim()} — use \${{ secrets.${name} }} instead.`,
          );
        }
      }
    }
  }
}

// ---------------------------------------------------------------------------
// YAML helpers
// ---------------------------------------------------------------------------

function yamlString(value: string): string {
  // Simple quoting — use single quotes and escape single quotes by doubling
  if (/^[a-zA-Z0-9._/-]+$/.test(value)) return value;
  return `'${value.replace(/'/g, "''")}'`;
}

// ---------------------------------------------------------------------------
// Errors
// ---------------------------------------------------------------------------

export class CiWorkflowError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "CiWorkflowError";
  }
}
